# ---------------------------------------------------------------------------
# Curva estática da planta: calculada uma única vez, em lote, para depois
# ser reaproveitada por interpolação em vez de chamar a rede neural a cada
# passo de simulação.
# ---------------------------------------------------------------------------
_U_GRID = np.linspace(LIMITE_INF_U, LIMITE_SUP_U, 401)

_entradas_grid = np.tile(estado_base, (len(_U_GRID), 1))
_entradas_grid[:, IDX_VARIAVEL_MANIPULADA] = _U_GRID
_entradas_grid_escalada = scaler.transform(_entradas_grid).astype("float32")
_Y_GRID = modelo(_entradas_grid_escalada, training=False).numpy().flatten()


def planta_caixa_preta(u):
    """Caixa-preta: devolve a pressão prevista para o sinal de controle 'u'
    (frequência do inversor), por interpolação na curva estática já
    calculada em _U_GRID / _Y_GRID."""
    return float(np.interp(np.clip(u, LIMITE_INF_U, LIMITE_SUP_U), _U_GRID, _Y_GRID))


