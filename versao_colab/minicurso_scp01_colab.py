"""### Passo 4 — Otimização automática dos ganhos

A função buscar_melhores_parametros faz uma busca em grade (grid search):
testa várias combinações de Kp, Ki e Kd e fica com a que minimiza o
overshoot obtido na simulação.

Cada simulação chama a RNA 1200 vezes, então essa busca é bem mais lenta
que uma simulação única. Por isso a grade já foi reduzida para 48
combinações (4 valores de Kp, 4 de Ki e 3 de Kd), o suficiente para caber
em poucos minutos.
"""

import random
import time

def buscar_melhores_parametros(
    geracoes_sem_melhora_max=8,
    geracoes_valor_repetido_max=5,
    tolerancia=0.5,
    custo_alvo=None,
    seed=42,
):
    """
    geracoes_sem_melhora_max: número de gerações consecutivas sem melhora
    significativa antes de considerar convergido.

    geracoes_valor_repetido_max: número de gerações consecutivas em que o
    melhor custo se repete exatamente, um critério mais rígido que indica
    estabilização total.

    tolerancia: variação mínima de custo para contar como melhora real.

    custo_alvo: se definido, encerra assim que o melhor custo atingir esse
    valor, independente dos demais critérios.

    seed: embaralha a ordem das combinações para os critérios de
    convergência não serem enviesados pela ordem original da grade.
    """
    combinacoes = [
        (kp, ki, kd)
        for kp in np.linspace(0.2, 3.0, 4)
        for ki in np.linspace(0.02, 0.3, 4)
        for kd in np.linspace(0.0, 0.2, 3)
    ]
    random.Random(seed).shuffle(combinacoes)

    total = len(combinacoes)
    melhor, melhor_custo = None, 1e9
    geracoes_sem_melhora = 0
    geracoes_valor_repetido = 0
    custo_anterior = None
    inicio = time.time()

    print(
        f"🧠 Otimização iniciada. Até {total} combinações, com convergência em "
        f"{geracoes_sem_melhora_max} gerações sem melhora ou "
        f"{geracoes_valor_repetido_max} gerações com valor repetido.",
        flush=True,
    )

    for i, (kp, ki, kd) in enumerate(combinacoes, start=1):
        decorrido = time.time() - inicio
        print(
            f"  [{i:02d}/{total}] Kp={kp:.2f} Ki={ki:.2f} Kd={kd:.2f} "
            f"({decorrido:.1f}s, sem melhora há {geracoes_sem_melhora}, "
            f"valor repetido há {geracoes_valor_repetido})",
            flush=True,
        )
        try:
            r = simular_planta(kp, ki, kd, plot=False)
            custo = r["overshoot"]
            if np.isnan(custo) or np.isinf(custo):
                print("    Custo inválido (nan ou inf), pulando.", flush=True)
                geracoes_sem_melhora += 1
                continue

            # houve melhora significativa, fora da tolerância?
            if custo < melhor_custo - tolerancia:
                melhor_custo, melhor = custo, r
                geracoes_sem_melhora = 0
                print(f"    Novo melhor custo: {custo:.2f}.", flush=True)
            else:
                geracoes_sem_melhora += 1

            # o melhor custo se manteve exatamente igual ao da geração anterior?
            if custo_anterior is not None and round(melhor_custo, 6) == round(custo_anterior, 6):
                geracoes_valor_repetido += 1
            else:
                geracoes_valor_repetido = 0
            custo_anterior = melhor_custo

        except Exception as e:
            print(f"    Erro nesta combinação: {e}", flush=True)
            geracoes_sem_melhora += 1
            continue

        if custo_alvo is not None and melhor_custo <= custo_alvo:
            print(
                f"🎯 Meta de custo atingida ({melhor_custo:.2f} <= {custo_alvo}). "
                f"Parando em {i}/{total}.",
                flush=True,
            )
            break

        if geracoes_sem_melhora >= geracoes_sem_melhora_max:
            print(
                f"🛑 Convergência por estagnação: {geracoes_sem_melhora_max} gerações "
                f"seguidas sem melhora. Parando em {i}/{total}.",
                flush=True,
            )
            break

        if geracoes_valor_repetido >= geracoes_valor_repetido_max:
            print(
                f"🛑 Convergência por valor repetido: melhor custo estável há "
                f"{geracoes_valor_repetido_max} gerações. Parando em {i}/{total}.",
                flush=True,
            )
            break

    total_tempo = time.time() - inicio
    if melhor is None:
        print(f"🧠 Otimização concluída em {total_tempo:.1f}s. Nenhuma combinação válida encontrada.", flush=True)
        return None

    print(
        f"🧠 Otimização concluída em {total_tempo:.1f}s. Melhor combinação: "
        f"Kp={melhor['Kp']:.2f} Ki={melhor['Ki']:.2f} Kd={melhor['Kd']:.2f} "
        f"(custo={melhor_custo:.2f}).",
        flush=True,
    )
    return simular_planta(melhor["Kp"], melhor["Ki"], melhor["Kd"], plot=True)


